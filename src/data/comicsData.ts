function createComicChapters(comicId: string, comicTitle: string, totalIssues: number): ChapterItem[] {
  const chapters: ChapterItem[] = [];
  for (let i = 1; i <= totalIssues; i++) {
    chapters.push({
      id: `${comicId}-issue-${i}`,
      comicId,
      chapterNumber: i,
      title: `Issue #${i}`,
      releaseDate: `202${Math.max(0, 4 - Math.floor(i / 10))}-${String((i % 12) + 1).padStart(2, '0')}-15`,
      scanlationGroup: 'Batcave HD Releases',
      pageCount: 24 + (i % 6) * 2,
    });
  }
  return chapters;
}

